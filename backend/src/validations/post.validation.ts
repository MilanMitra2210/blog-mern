import Joi from 'joi';

export const createPostSchema = Joi.object({
  title: Joi.string().trim().min(3).max(500).required().messages({
    'string.empty': 'Title is required',
    'string.min': 'Title must be at least 3 characters',
  }),
  slug: Joi.string().trim().max(500).optional(),
  excerpt: Joi.string().allow('').optional(),
  content: Joi.string().allow('').optional(),
  isPublished: Joi.boolean().optional(),
  isFeatured: Joi.boolean().optional(),
  displayOrder: Joi.number().optional(),
  category: Joi.string().allow(null, '').optional(),
  categoryId: Joi.string().allow(null, '').optional(),
  author: Joi.any().optional(),
  authorId: Joi.string().allow(null, '').optional(),
  bannerImage: Joi.any().optional(),
  bannerImageId: Joi.string().allow(null, '').optional(),
  sections: Joi.array().optional(),
  seo: Joi.object().optional(),
  tags: Joi.array().optional(),
  tagIds: Joi.array().optional(),
  publishDate: Joi.date().optional(),
}).unknown(true);

